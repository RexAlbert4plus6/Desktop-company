const { contextBridge, ipcRenderer,webUtils } = require('electron');
contextBridge.exposeInMainWorld('kairos', {
  load: () => ipcRenderer.invoke('load'),
  openCompanion:()=>ipcRenderer.invoke('companion-open'),
  companionState:()=>ipcRenderer.invoke('companion-state'),
  companionStart:()=>ipcRenderer.invoke('companion-start'),
  companionStop:()=>ipcRenderer.invoke('companion-stop'),
  companionSave:value=>ipcRenderer.invoke('companion-save',value),
  companionSpeak:reason=>ipcRenderer.invoke('companion-speak',reason),
  hideCompanionToast:()=>ipcRenderer.invoke('companion-hide-toast'),
  onCompanionState:callback=>{ipcRenderer.on('companion-state',(_,value)=>callback(value));},
  onCompanionLine:callback=>{ipcRenderer.on('companion-line',(_,value)=>callback(value));},
  enterCat:()=>ipcRenderer.invoke('enter-cat'),
  returnHuman:()=>ipcRenderer.invoke('return-human'),
  catArtwork:()=>ipcRenderer.invoke('cat-artwork'),
  onCatFrame:callback=>{ipcRenderer.on('cat-frame',(_,frame)=>callback(frame));},
  save: value => ipcRenderer.invoke('save', value),
  send: text => ipcRenderer.invoke('send', text),
  cancel: () => ipcRenderer.invoke('cancel'),
  test: () => ipcRenderer.invoke('test'),
  toggleChat: () => ipcRenderer.invoke('toggle-chat'),
  hideChat: () => ipcRenderer.invoke('hide-chat'),
  menu: () => ipcRenderer.invoke('menu'),
  drag: phase => ipcRenderer.send('drag', phase),
  openSettings: () => ipcRenderer.invoke('open-settings'),
  summarize: () => ipcRenderer.invoke('summarize'),
  selectExpression: id => ipcRenderer.invoke('select-expression', id),
  switchCharacter:index=>ipcRenderer.invoke('switch-character',index),
  importImage:(slot,asset,file)=>ipcRenderer.invoke('import-image',{slot,asset,filePath:file?webUtils.getPathForFile(file):''}),
  importCharacter:()=>ipcRenderer.invoke('import-character'),
  exportCharacter:()=>ipcRenderer.invoke('export-character'),
  characterFolder:()=>ipcRenderer.invoke('character-folder'),
  toggleAccessory:id=>ipcRenderer.invoke('accessory',id),
  headpat:(phase,kind)=>ipcRenderer.send('headpat',{phase,kind}),
  exportChat: () => ipcRenderer.invoke('export'),
  dataFolder: () => ipcRenderer.invoke('data-folder'),
  clear: () => ipcRenderer.invoke('clear'),
  onSettings: callback => {ipcRenderer.on('settings', () => callback());},
  onGreeting: callback => {ipcRenderer.on('greeting', (_, value) => callback(value));},
  onState: callback => {ipcRenderer.on('state', (_, value) => callback(value));},
  onExpression: callback => {ipcRenderer.on('expression', (_, value) => callback(value));},
  onArtwork:callback=>{ipcRenderer.on('artwork',(_,value)=>callback(value));},
  onLocalLine:callback=>{ipcRenderer.on('local-line',(_,value)=>callback(value));}
});
